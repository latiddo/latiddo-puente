# Latiddo - Claude usage bridge installer for Windows (Latiddo Pulse, Latiddo robot or both).
#
# One line (PowerShell):
#   & ([scriptblock]::Create((irm https://releases.latiddo.com/pulse/bridge/install.ps1))) --ip 192.168.1.50
#   ... --robot latiddo-xxxx.local                   (the robot only)
#   ... --ip 192.168.1.50 --robot latiddo-xxxx.local (both: one bridge, one task)
#   ... (no arguments)                                (asks: Pulse, robot or both)
# From a local copy of the repository (no download):
#   .\install.ps1 -LocalPath C:\path\to\repository --ip 192.168.1.50
#
# It downloads the bridge scripts, checks their SHA-256 against the list below,
# saves them in %LOCALAPPDATA%\Latiddo and runs:
#   python latiddo_usage_poll.py --setup --lang <es|en> <your other arguments>
# If Python 3 or Claude Code is missing it offers to install it (Python with winget, Claude
# Code with its official installer) and only does so when you answer y (s in Spanish).
# Without a terminal, or with --yes or --dry-run, it never installs anything: it says what is
# missing. --install-missing installs them without asking.
# No tokens, no credentials, no telemetry. It never closes your PowerShell window:
# the result is in $LASTEXITCODE (0 = OK).
#
# Language: English or Spanish. -Lang es|en (or --lang) forces it; otherwise the language
# already saved for the bridge (lang in %USERPROFILE%\.claude\latiddo.json), else the Windows
# display language of the user. The bridge gets the same one (--lang), so its questions match.
# The Spanish texts are written with \uXXXX escapes: the file stays ASCII, so it reads the same
# in Windows PowerShell 5.1 whatever the encoding of the download.
#
# Test without uninstalling anything: LATIDDO_TEST_MISSING=python, claude or python,claude
# acts as if that program were missing. It asks the same questions, but never installs
# anything, never copies the scripts and never runs the setup:
#   $env:LATIDDO_TEST_MISSING = 'claude'; .\install.ps1 -LocalPath . --ip 192.168.1.50
#   Remove-Item Env:LATIDDO_TEST_MISSING

# Where the files are downloaded from: the release site, with the bridge scripts side by
# side (tools/make-release.py builds that folder).
$DefaultBaseUrl = "https://releases.latiddo.com/pulse/bridge"
$ClaudeInstallCmd = 'irm https://claude.ai/install.ps1 | iex'
$PythonWingetArgs = @('install', '-e', '--id', 'Python.Python.3.12', '--accept-source-agreements', '--accept-package-agreements')

# BEGIN HASHES (generated by tools/generate_hashes.py; LF line endings)
$Hashes = [ordered]@{
    'latiddo_statusline.py' = 'd07ed880351d5083e01d643f2fca2013bc94e9df96c309d719a94115307884ec'
    'latiddo_usage_poll.py' = '1ab48c9bc63bae8b55960b111831864c06025bfb6784ca1aaefddf2898740b47'
}
# END HASHES

# --- Language ---------------------------------------------------------------------
$LatiddoLang = 'en'

# The text in the current language: L "English" "Spanish, with \u00e1-style escapes".
function L([string]$En, [string]$Es) {
    if ($LatiddoLang -ne 'es') { return $En }
    return [regex]::Replace($Es, '\\u([0-9a-fA-F]{4})', { param($m) [string][char][Convert]::ToInt32($m.Groups[1].Value, 16) })
}

# "es" or "en" saved for the bridge (the EN / ES selector of its settings page, or --lang), or "".
function Get-LatiddoSavedLang {
    try {
        $cfg = Join-Path $env:USERPROFILE '.claude\latiddo.json'
        $v = [string]((Get-Content -Raw -LiteralPath $cfg -ErrorAction Stop | ConvertFrom-Json).lang)
        if ($v -eq 'es' -or $v -eq 'en') { return $v }
    } catch { }
    return ''
}

# The Windows display language of the user (the same one the bridge uses when nothing is saved).
function Get-LatiddoSystemLang {
    try { if ([Globalization.CultureInfo]::CurrentUICulture.TwoLetterISOLanguageName -eq 'es') { return 'es' } } catch { }
    return 'en'
}

# Takes -Lang / --lang out of the arguments and sets $LatiddoLang. Returns the other arguments.
function Initialize-LatiddoLang([object[]]$Arguments) {
    $rest = @()
    $forced = $null
    for ($i = 0; $i -lt $Arguments.Count; $i++) {
        $a = [string]$Arguments[$i]
        if ($a -ieq '-Lang' -or $a -ieq '-Lang:' -or $a -ieq '--lang') {
            $forced = if ($i + 1 -lt $Arguments.Count) { ([string]$Arguments[++$i]).Trim().ToLower() } else { '' }
        }
        elseif ($a -like '--lang=*') { $forced = $a.Substring(7).Trim().ToLower() }
        else { $rest += $a }
    }
    $saved = Get-LatiddoSavedLang
    if ($null -ne $forced -and $forced -ne 'es' -and $forced -ne 'en') {
        $forced = $null
        Set-Variable -Name LatiddoLangError -Value $true -Scope 1
    }
    $value = if ($forced) { $forced } elseif ($saved) { $saved } else { Get-LatiddoSystemLang }
    Set-Variable -Name LatiddoLang -Value $value -Scope 1
    return , $rest
}

function Invoke-LatiddoInstall([object[]]$Arguments, [hashtable]$Result) {
    $ErrorActionPreference = 'Stop'
    $ProgressPreference = 'SilentlyContinue'
    $NewWindow = L "Then close this window, open a new PowerShell window and run the command again." `
                   "Despu\u00e9s cierra esta ventana, abre una ventana de PowerShell nueva y vuelve a ejecutar el comando."

    # -LocalPath <dir>, -BaseUrl <url> and --install-missing are for this script (-Lang was
    # taken out before); everything else goes to --setup. (No param() block: it would bind
    # the --setup arguments by position.)
    $LocalPath = ""
    $BaseUrl = $DefaultBaseUrl
    $InstallMissing = $false
    $SetupArgs = @()
    for ($i = 0; $i -lt $Arguments.Count; $i++) {
        $a = [string]$Arguments[$i]
        if ($a -ieq '-LocalPath' -and $i + 1 -lt $Arguments.Count) { $LocalPath = [string]$Arguments[++$i] }
        elseif ($a -ieq '-BaseUrl' -and $i + 1 -lt $Arguments.Count) { $BaseUrl = [string]$Arguments[++$i] }
        elseif ($a -ieq '--install-missing') { $InstallMissing = $true }
        else { $SetupArgs += $a }
    }
    $Dest = Join-Path $env:LOCALAPPDATA 'Latiddo'

    # Test mode (LATIDDO_TEST_MISSING): act as if Python and/or Claude Code were missing,
    # without installing, copying or setting up anything.
    $TestMissing = ([string]$env:LATIDDO_TEST_MISSING).Trim()
    $TestMode = [bool]$TestMissing
    $TestPython = $TestMissing -match 'python'
    $TestClaude = $TestMissing -match 'claude'
    if ($TestMode) {
        Write-Host (L "Test (LATIDDO_TEST_MISSING=$TestMissing): nothing will be installed, copied or changed." `
                      "Prueba (LATIDDO_TEST_MISSING=$TestMissing): no se instala, no se copia ni se cambia nada.") -ForegroundColor Cyan
    }

    # Installing anything needs a y from a person at a terminal (or --install-missing).
    # --yes and --dry-run (also --install-task) never install: they only report what is missing.
    $Unattended = $false
    $ClaudePathIdx = -1
    for ($i = 0; $i -lt $SetupArgs.Count; $i++) {
        $a = [string]$SetupArgs[$i]
        if ($a -ieq '--yes' -or $a -ieq '--dry-run' -or $a -ieq '--install-task') { $Unattended = $true }
        elseif ($a -ieq '--claude-path' -and $i + 1 -lt $SetupArgs.Count) { $ClaudePathIdx = $i + 1 }
    }
    $Interactive = $false
    try { $Interactive = [Environment]::UserInteractive -and -not [Console]::IsInputRedirected } catch { }

    # $true: install without asking. $false: do not install. Otherwise ask (y / s = install).
    function Confirm-Install([string]$Question) {
        if ($InstallMissing) { return $true }
        if ($Unattended -or -not $Interactive) { return $false }
        $answer = Read-Host ("$Question " + (L "[y/N]" "[s/N]"))
        return ([string]$answer).Trim().ToLower() -match '^(y|yes|s|si|s\u00ed)$'
    }

    # Reload PATH from the registry (Machine + User) so a program installed just now is found
    # in this window; entries added only to this session are kept at the end.
    function Update-SessionPath {
        $fresh = @()
        foreach ($scope in 'Machine', 'User') {
            $v = [Environment]::GetEnvironmentVariable('Path', $scope)
            if ($v) { $fresh += $v.Split(';') | Where-Object { $_ } }
        }
        foreach ($p in ([string]$env:Path).Split(';')) {
            if ($p -and $fresh -notcontains $p) { $fresh += $p }
        }
        $env:Path = $fresh -join ';'
    }

    function Find-Python {
        if ($TestPython) { return $null }
        foreach ($c in @(@('py', '-3'), @('python'), @('python3'))) {
            $exe = $c[0]
            $pre = @($c | Select-Object -Skip 1)
            if (-not (Get-Command $exe -CommandType Application -ErrorAction SilentlyContinue)) { continue }
            try {
                $out = & $exe @pre -c "import sys; print('%d.%d' % sys.version_info[:2]); print(sys.executable)" 2>$null
            } catch { continue }
            if ($LASTEXITCODE -ne 0 -or -not $out -or @($out).Count -lt 2) { continue }
            $parts = ([string]$out[0]).Split('.')
            if ($parts.Count -ge 2 -and [int]$parts[0] -eq 3 -and [int]$parts[1] -ge 8) { return [string]$out[1] }
        }
        return $null
    }

    # Same places as find_claude() in latiddo_usage_poll.py. $Given: the --claude-path value.
    function Find-Claude([string]$Given) {
        if ($TestClaude) { return $null }
        if ($Given) { if (Test-Path -LiteralPath $Given -PathType Leaf) { return $Given } else { return $null } }
        $cfg = Join-Path $env:USERPROFILE '.claude\latiddo.json'
        try {
            $saved = [string]((Get-Content -Raw -LiteralPath $cfg -ErrorAction Stop | ConvertFrom-Json).claude_path)
            if ($saved -and (Test-Path -LiteralPath $saved -PathType Leaf)) { return $saved }
        } catch { }
        $cmd = Get-Command claude -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($cmd) { return $cmd.Source }
        $candidates = @((Join-Path $env:USERPROFILE '.local\bin\claude.exe'))
        if ($env:APPDATA) { $candidates += (Join-Path $env:APPDATA 'npm\claude.cmd') }
        foreach ($c in $candidates) { if (Test-Path -LiteralPath $c -PathType Leaf) { return $c } }
        return $null
    }

    # --- Python 3 -----------------------------------------------------------------
    $Python = Find-Python
    if (-not $Python) {
        $missing = (L ("Python 3 (3.8 or newer) is required and was not found.`n" +
                       "Install it from https://www.python.org/downloads/ (tick 'Add python.exe to PATH'),`n" +
                       "or run:  winget install -e --id Python.Python.3.12`n") `
                      ("Hace falta Python 3 (3.8 o posterior) y no se ha encontrado.`n" +
                       "Inst\u00e1lalo desde https://www.python.org/downloads/ (marca 'Add python.exe to PATH')`n" +
                       "o ejecuta:  winget install -e --id Python.Python.3.12`n")) + $NewWindow
        Write-Host (L "Python 3 (3.8 or newer) was not found." "No se ha encontrado Python 3 (3.8 o posterior).") -ForegroundColor Yellow
        if (Confirm-Install (L "Install Python 3.12 now with winget?" "\u00bfInstalar ahora Python 3.12 con winget?")) {
            if ($TestMode) {
                Write-Host (L "Test: nothing is installed." "Prueba: no se instala nada.") -ForegroundColor Cyan
            } elseif (-not (Get-Command winget -CommandType Application -ErrorAction SilentlyContinue)) {
                Write-Host (L "winget is not available on this computer." "winget no est\u00e1 disponible en este ordenador.") -ForegroundColor Yellow
            } else {
                Write-Host ((L "Running:" "Ejecutando:") + " winget $($PythonWingetArgs -join ' ')")
                & winget @PythonWingetArgs
                if ($LASTEXITCODE -ne 0) {
                    Write-Host (L "winget finished with code $LASTEXITCODE." "winget ha terminado con el c\u00f3digo $LASTEXITCODE.") -ForegroundColor Yellow
                }
                Update-SessionPath
                $Python = Find-Python
            }
        }
        if (-not $Python) { throw $missing }
    }
    Write-Host "Python: $Python"

    # --- Files ----------------------------------------------------------------------
    $Tmp = Join-Path ([IO.Path]::GetTempPath()) ("latiddo-" + [guid]::NewGuid().ToString('N'))
    New-Item -ItemType Directory -Path $Tmp -Force | Out-Null
    try {
        $Source = $null
        if ($LocalPath) {
            $Source = $LocalPath
            if (Test-Path (Join-Path $LocalPath 'claude-bridge')) { $Source = Join-Path $LocalPath 'claude-bridge' }
            Write-Host (L "Using local files from $Source" "Se usan los archivos locales de $Source")
        } else {
            [Net.ServicePointManager]::SecurityProtocol = [Net.ServicePointManager]::SecurityProtocol -bor [Net.SecurityProtocolType]::Tls12
            Write-Host (L "Downloading from $BaseUrl" "Descargando de $BaseUrl")
        }

        $Verified = [ordered]@{}
        foreach ($name in $Hashes.Keys) {
            $file = Join-Path $Tmp $name
            if ($LocalPath) {
                $src = Join-Path $Source $name
                if (-not (Test-Path $src)) { throw (L "Missing file: $src" "Falta el archivo: $src") }
                Copy-Item $src $file
            } else {
                try {
                    Invoke-WebRequest -UseBasicParsing -Uri "$BaseUrl/$name" -OutFile $file
                } catch {
                    throw ((L "Could not download $BaseUrl/$name" "No se ha podido descargar $BaseUrl/$name") + "`n$($_.Exception.Message)")
                }
            }
            # SHA-256 of the file with CRLF turned into LF (as stored in the repository);
            # the normalized bytes are what gets installed.
            $bytes = [IO.File]::ReadAllBytes($file)
            $norm = New-Object System.Collections.Generic.List[byte] ($bytes.Length)
            for ($j = 0; $j -lt $bytes.Length; $j++) {
                if ($bytes[$j] -eq 13 -and $j + 1 -lt $bytes.Length -and $bytes[$j + 1] -eq 10) { continue }
                $norm.Add($bytes[$j])
            }
            $arr = $norm.ToArray()
            $hash = -join ([Security.Cryptography.SHA256]::Create().ComputeHash($arr) | ForEach-Object { $_.ToString('x2') })
            if ($hash -ne $Hashes[$name]) {
                throw (L ("Checksum mismatch for $name. Nothing was installed.`n" +
                          "  expected $($Hashes[$name])`n  got      $hash") `
                         ("El SHA-256 de $name no coincide. No se ha instalado nada.`n" +
                          "  esperado $($Hashes[$name])`n  obtenido $hash"))
            }
            $Verified[$name] = $arr
            Write-Host ("  $name  " + (L "OK (SHA-256 verified)" "OK (SHA-256 comprobado)"))
        }

        if ($TestMode) {
            Write-Host (L "Test: the files were checked but not copied to $Dest." `
                         "Prueba: los archivos se han comprobado, pero no se copian a $Dest.") -ForegroundColor Cyan
        } else {
            New-Item -ItemType Directory -Path $Dest -Force | Out-Null
            foreach ($name in $Verified.Keys) {
                [IO.File]::WriteAllBytes((Join-Path $Dest $name), $Verified[$name])
            }
            Write-Host (L "Installed in $Dest" "Instalado en $Dest")
        }
    } finally {
        Remove-Item -Recurse -Force $Tmp -ErrorAction SilentlyContinue
    }

    # --- Claude Code ------------------------------------------------------------------
    # The setup checks that it is signed in, and offers to sign in if it is not.
    $Given = if ($ClaudePathIdx -ge 0) { [string]$SetupArgs[$ClaudePathIdx] } else { "" }
    $Claude = Find-Claude $Given
    if (-not $Claude) {
        Write-Host ""
        if ($Given) {
            Write-Host (L "Claude Code was not found at $Given (--claude-path)." `
                          "No se ha encontrado Claude Code en $Given (--claude-path).") -ForegroundColor Yellow
        } else {
            Write-Host (L "Claude Code (the claude command) was not found." `
                          "No se ha encontrado Claude Code (el comando claude).") -ForegroundColor Yellow
        }
        Write-Host ((L "It can be installed with its official installer:" "Se puede instalar con su instalador oficial:") + "  $ClaudeInstallCmd")
        if (Confirm-Install (L "Install it now with the official installer?" "\u00bfInstalarlo ahora con el instalador oficial?")) {
            if ($TestMode) {
                Write-Host (L "Test: nothing is installed." "Prueba: no se instala nada.") -ForegroundColor Cyan
            } else {
                Write-Host ((L "Running:" "Ejecutando:") + " $ClaudeInstallCmd")
                # In a child PowerShell, so nothing the installer does can close this window
                $ps = (Get-Process -Id $PID).Path
                & $ps -NoProfile -ExecutionPolicy Bypass -Command $ClaudeInstallCmd
                if ($LASTEXITCODE -ne 0) {
                    Write-Host (L "The Claude Code installer finished with code $LASTEXITCODE." `
                                  "El instalador de Claude Code ha terminado con el c\u00f3digo $LASTEXITCODE.") -ForegroundColor Yellow
                }
                Update-SessionPath
                $Claude = Find-Claude ""
                if ($Claude -and $Given) {
                    Write-Host (L "Using $Claude instead of $Given." "Se usa $Claude en lugar de $Given.")
                    $SetupArgs[$ClaudePathIdx] = $Claude
                }
            }
        }
        if (-not $Claude) {
            throw ((L ("Claude Code (the claude command) is required and was not found.`n" +
                       "Install it from https://claude.com/claude-code, in PowerShell:  $ClaudeInstallCmd`n" +
                       "If it is already installed somewhere else, add --claude-path <path to claude>.`n") `
                      ("Hace falta Claude Code (el comando claude) y no se ha encontrado.`n" +
                       "Inst\u00e1lalo desde https://claude.com/claude-code; en PowerShell:  $ClaudeInstallCmd`n" +
                       "Si ya est\u00e1 instalado en otro sitio, a\u00f1ade --claude-path <ruta de claude>.`n")) + $NewWindow)
        }
    }
    Write-Host "Claude Code: $Claude"

    if ($TestMode) {
        Write-Host ""
        Write-Host (L "Test finished: nothing was installed or changed, and the setup did not run." `
                      "Prueba terminada: no se ha instalado ni cambiado nada, y la configuraci\u00f3n no se ha ejecutado.") -ForegroundColor Cyan
        $Result.Code = 0
        return
    }

    # --- Setup ----------------------------------------------------------------------
    Write-Host ""
    # The bridge gets the same language (--lang, saved in latiddo.json). Called as a plain
    # statement (output not captured), so prompts and messages reach the console.
    & $Python (Join-Path $Dest 'latiddo_usage_poll.py') --setup --lang $LatiddoLang @SetupArgs
    $Result.Code = $LASTEXITCODE
}

# No "exit": with the one-line form this runs inside your PowerShell session, and
# exit would close the window. The result goes to $LASTEXITCODE instead.
$LatiddoResult = @{ Code = 1 }
$LatiddoLangError = $false
try {
    $LatiddoArgs = Initialize-LatiddoLang $args
    if ($LatiddoLangError) { throw (L "-Lang must be es or en." "-Lang tiene que ser es o en.") }
    Invoke-LatiddoInstall $LatiddoArgs $LatiddoResult
} catch {
    Write-Host ""
    Write-Host $_.Exception.Message -ForegroundColor Red
    $LatiddoResult.Code = 1
}
$global:LASTEXITCODE = $LatiddoResult.Code
if ($LatiddoResult.Code -ne 0) {
    Write-Host ""
    Write-Host (L "Setup did not finish (code $($LatiddoResult.Code)). See the message above." `
                  "La instalaci\u00f3n no ha terminado (c\u00f3digo $($LatiddoResult.Code)). Mira el mensaje de arriba.") -ForegroundColor Yellow
}
