# Latiddo - Claude usage bridge installer for macOS and Linux (Latiddo Pulse, Latiddo robot or both).
#
# One line:
#   curl -fsSL https://releases.latiddo.com/pulse/bridge/install.sh | sh -s -- --ip 192.168.1.50
#   ... | sh -s -- --robot latiddo-xxxx.local                   (the robot only)
#   ... | sh -s -- --ip 192.168.1.50 --robot latiddo-xxxx.local (both: one bridge, one task)
#   ... | sh                                                    (asks: Pulse, robot or both)
# From a local copy of the repository (no download):
#   sh install.sh --local /path/to/repository --ip 192.168.1.50
#
# It downloads the bridge scripts, checks their SHA-256 against the list below,
# saves them in ~/.local/share/latiddo and runs:
#   python3 latiddo_usage_poll.py --setup --lang <es|en> <your other arguments>
# If Claude Code is missing it offers to install it with its official installer, and only
# does so when you answer y (s in Spanish). Without a terminal, or with --yes or --dry-run, it
# never installs anything: it says what is missing. --install-missing installs it without asking.
# No tokens, no credentials, no telemetry.
#
# Language: English or Spanish. --lang es|en forces it; otherwise the language already saved
# for the bridge (lang in ~/.claude/latiddo.json), else the system language (LC_ALL,
# LC_MESSAGES, LANG, LANGUAGE; on macOS, AppleLanguages if none is set), the same order as the
# bridge. The bridge gets the same one (--lang), so its questions match.
#
# Test without uninstalling anything: LATIDDO_TEST_MISSING=python, claude or python,claude
# acts as if that program were missing. It asks the same questions, but never installs
# anything, never copies the scripts and never runs the setup:
#   LATIDDO_TEST_MISSING=claude sh install.sh --local . --ip 192.168.1.50
set -eu

# Where the files are downloaded from: the release site, with the bridge scripts side by
# side (tools/make-release.py builds that folder).
BASE_URL="https://releases.latiddo.com/pulse/bridge"
CLAUDE_INSTALL_CMD="curl -fsSL https://claude.ai/install.sh | bash"

# BEGIN HASHES (generated by tools/generate_hashes.py; LF line endings)
HASHES='
361b756f26173a4a171a48b45863055800268f653e90d1dbc6830660736b9e66  latiddo_statusline.py
1ab48c9bc63bae8b55960b111831864c06025bfb6784ca1aaefddf2898740b47  latiddo_usage_poll.py
'
# END HASHES

DEST="${XDG_DATA_HOME:-$HOME/.local/share}/latiddo"
LOCAL=""
INSTALL_MISSING=0

# --- Language ---------------------------------------------------------------------
# "es" or "en" saved for the bridge (its settings page or --lang), or nothing.
saved_lang() {
    f="$HOME/.claude/latiddo.json"
    [ -f "$f" ] || return 0
    v=$(grep -o '"lang"[[:space:]]*:[[:space:]]*"[a-z]*"' "$f" 2>/dev/null | head -n 1 |
        sed 's/.*"\([a-z]*\)"$/\1/') || v=""
    case $v in es|en) printf '%s\n' "$v" ;; esac
}
# The system language, the same way as system_lang() in latiddo_statusline.py.
system_lang() {
    for v in "${LC_ALL:-}" "${LC_MESSAGES:-}" "${LANG:-}" "${LANGUAGE:-}"; do
        [ -n "$v" ] || continue
        case ${v%%.*} in C|POSIX) continue ;; esac
        case $v in [Ee][Ss]*) echo es ;; *) echo en ;; esac
        return 0
    done
    if [ "$(uname -s 2>/dev/null)" = Darwin ]; then
        first=$(defaults read -g AppleLanguages 2>/dev/null | tr -d '()", ' | sed -n '/./{p;q;}') || first=""
        case $first in [Ee][Ss]*) echo es; return 0 ;; esac
    fi
    echo en
}
# --lang before anything else, so every message is in the right language.
FORCED=""
LANG_BAD=0
prev=""
for a in "$@"; do
    case $a in --lang=*) FORCED=${a#--lang=} ;; esac
    [ "$prev" = "--lang" ] && FORCED=$a
    prev=$a
done
[ "$prev" = "--lang" ] && LANG_BAD=1
case $FORCED in ""|es|en) ;; *) FORCED=""; LANG_BAD=1 ;; esac
UI_LANG=$FORCED
[ -n "$UI_LANG" ] || UI_LANG=$(saved_lang)
[ -n "$UI_LANG" ] || UI_LANG=$(system_lang)

# The text in the current language: L "English" "Spanish"
L() { if [ "$UI_LANG" = es ]; then printf '%s' "$2"; else printf '%s' "$1"; fi; }

NEW_WINDOW=$(L "Then close this terminal window, open a new one and run the command again." \
               "Después cierra esta ventana de terminal, abre otra y vuelve a ejecutar el comando.")

fail() { printf '\n%s\n' "$*" >&2; exit 1; }

[ "$LANG_BAD" = 0 ] || fail "$(L "--lang must be es or en." "--lang tiene que ser es o en.")"

# --local PATH, --base-url URL, --install-missing and --lang are for this script; everything
# else goes to --setup (--lang goes too, with the language chosen here).
n=$#
while [ "$n" -gt 0 ]; do
    a=$1; shift; n=$((n - 1))
    case $a in
        --local)      [ "$n" -gt 0 ] || fail "$(L "--local needs a path" "--local necesita una ruta")"
                      LOCAL=$1; shift; n=$((n - 1)) ;;
        --local=*)    LOCAL=${a#--local=} ;;
        --base-url)   [ "$n" -gt 0 ] || fail "$(L "--base-url needs a URL" "--base-url necesita una URL")"
                      BASE_URL=$1; shift; n=$((n - 1)) ;;
        --base-url=*) BASE_URL=${a#--base-url=} ;;
        --install-missing) INSTALL_MISSING=1 ;;
        --lang)       shift; n=$((n - 1)) ;;
        --lang=*)     ;;
        *)            set -- "$@" "$a" ;;
    esac
done

# Test mode (LATIDDO_TEST_MISSING): act as if Python and/or Claude Code were missing, without
# installing, copying or setting up anything.
TEST_MISSING=${LATIDDO_TEST_MISSING:-}
TEST_PYTHON=0; TEST_CLAUDE=0
case $TEST_MISSING in *python*) TEST_PYTHON=1 ;; esac
case $TEST_MISSING in *claude*) TEST_CLAUDE=1 ;; esac
if [ -n "$TEST_MISSING" ]; then
    L "Test (LATIDDO_TEST_MISSING=$TEST_MISSING): nothing will be installed, copied or changed." \
      "Prueba (LATIDDO_TEST_MISSING=$TEST_MISSING): no se instala, no se copia ni se cambia nada."
    echo
fi

# --- Python 3 ---------------------------------------------------------------------
PY=""
if [ "$TEST_PYTHON" = 0 ]; then
    for c in python3 python; do
        if command -v "$c" >/dev/null 2>&1 &&
           "$c" -c 'import sys; sys.exit(0 if sys.version_info >= (3, 8) else 1)' >/dev/null 2>&1; then
            PY=$(command -v "$c"); break
        fi
    done
fi
if [ -z "$PY" ]; then
    case $(uname -s) in
        Darwin) how=$(L "Install it from https://www.python.org/downloads/ (the macOS installer),
or with Homebrew:  brew install python
or with Apple's command line tools:  xcode-select --install" \
"Instálalo desde https://www.python.org/downloads/ (el instalador de macOS),
con Homebrew:  brew install python
o con las herramientas de línea de comandos de Apple:  xcode-select --install") ;;
        *)      how=$(L "Install it with your package manager, for example:" \
                        "Instálalo con el gestor de paquetes de tu sistema, por ejemplo:")"
  Debian/Ubuntu:  sudo apt install python3
  Fedora:         sudo dnf install python3
  Arch:           sudo pacman -S python" ;;
    esac
    fail "$(L "Python 3 (3.8 or newer) is required and was not found." \
              "Hace falta Python 3 (3.8 o posterior) y no se ha encontrado.")
$how
$NEW_WINDOW"
fi
echo "Python: $PY"

# --- Files -----------------------------------------------------------------------
# Turn CRLF into LF in place (the form stored in the repository) and print the SHA-256.
# The normalized file is what gets installed.
normalize_sha256() {
    "$PY" -c 'import hashlib, sys
p = sys.argv[1]
b = open(p, "rb").read().replace(b"\r\n", b"\n")
open(p, "wb").write(b)
print(hashlib.sha256(b).hexdigest())' "$1"
}
fetch() {
    if command -v curl >/dev/null 2>&1; then curl -fsSL "$1" -o "$2"
    elif command -v wget >/dev/null 2>&1; then wget -q "$1" -O "$2"
    else fail "$(L "curl or wget is required to download the files." \
                   "Hace falta curl o wget para descargar los archivos.")"
    fi
}

TMP=$(mktemp -d 2>/dev/null || mktemp -d -t latiddo)
trap 'rm -rf "$TMP"' EXIT INT TERM

SRC=""
if [ -n "$LOCAL" ]; then
    SRC=$LOCAL
    [ -d "$LOCAL/claude-bridge" ] && SRC="$LOCAL/claude-bridge"
    L "Using local files from $SRC" "Se usan los archivos locales de $SRC"; echo
else
    L "Downloading from $BASE_URL" "Descargando de $BASE_URL"; echo
fi

NAMES=$(printf '%s\n' "$HASHES" | awk 'NF == 2 { print $2 }')
for name in $NAMES; do
    expected=$(printf '%s\n' "$HASHES" | awk -v n="$name" '$2 == n { print $1 }')
    if [ -n "$SRC" ]; then
        [ -f "$SRC/$name" ] || fail "$(L "Missing file: $SRC/$name" "Falta el archivo: $SRC/$name")"
        cp "$SRC/$name" "$TMP/$name"
    else
        fetch "$BASE_URL/$name" "$TMP/$name" ||
            fail "$(L "Could not download $BASE_URL/$name" "No se ha podido descargar $BASE_URL/$name")"
    fi
    got=$(normalize_sha256 "$TMP/$name")
    [ "$got" = "$expected" ] || fail "$(L "Checksum mismatch for $name. Nothing was installed.
  expected $expected
  got      $got" "El SHA-256 de $name no coincide. No se ha instalado nada.
  esperado $expected
  obtenido $got")"
    echo "  $name  $(L "OK (SHA-256 verified)" "OK (SHA-256 comprobado)")"
done

if [ -n "$TEST_MISSING" ]; then
    L "Test: the files were checked but not copied to $DEST." \
      "Prueba: los archivos se han comprobado, pero no se copian a $DEST."; echo
else
    mkdir -p "$DEST"
    for name in $NAMES; do
        cp "$TMP/$name" "$DEST/$name"
    done
    L "Installed in $DEST" "Instalado en $DEST"; echo
fi

# --- Claude Code -----------------------------------------------------------------
# The setup checks that it is signed in, and offers to sign in if it is not.
# Installing needs a y (or s) typed at the terminal (or --install-missing); --yes, --dry-run
# and --install-task never install.
UNATTENDED=0
GIVEN=""
prev=""
for a in "$@"; do
    case $a in
        --yes|--dry-run|--install-task) UNATTENDED=1 ;;
        --claude-path=*) GIVEN=${a#--claude-path=} ;;
    esac
    [ "$prev" = "--claude-path" ] && GIVEN=$a
    prev=$a
done
TTY=0
if (: < /dev/tty) 2>/dev/null && (: > /dev/tty) 2>/dev/null; then TTY=1; fi

# Same places as find_claude() in latiddo_usage_poll.py. $1: the --claude-path value.
find_claude() {
    [ "$TEST_CLAUDE" = 0 ] || return 0
    if [ -n "${1:-}" ]; then
        [ -f "$1" ] && printf '%s\n' "$1"
        return 0
    fi
    saved=$("$PY" -c 'import json, os, sys
try:
    p = json.load(open(os.path.expanduser("~/.claude/latiddo.json"))).get("claude_path") or ""
except Exception:
    p = ""
print(p if p and os.path.isfile(p) else "")' 2>/dev/null || true)
    if [ -n "$saved" ]; then printf '%s\n' "$saved"; return 0; fi
    if command -v claude >/dev/null 2>&1; then command -v claude; return 0; fi
    for c in "$HOME/.local/bin/claude" /opt/homebrew/bin/claude /usr/local/bin/claude; do
        if [ -f "$c" ]; then printf '%s\n' "$c"; return 0; fi
    done
}

# 0 = install, 1 = do not. Asks on the terminal unless --install-missing.
confirm_install() {
    [ "$INSTALL_MISSING" = 1 ] && return 0
    [ "$UNATTENDED" = 0 ] && [ "$TTY" = 1 ] || return 1
    printf '%s %s ' "$1" "$(L "[y/N]" "[s/N]")" > /dev/tty
    answer=""
    read -r answer < /dev/tty || answer=""
    case $answer in y|Y|yes|YES|Yes|s|S|si|SI|Si|sí|SÍ|Sí) return 0 ;; esac
    return 1
}

CLAUDE=$(find_claude "$GIVEN")
if [ -z "$CLAUDE" ]; then
    echo
    if [ -n "$GIVEN" ]; then L "Claude Code was not found at $GIVEN (--claude-path)." \
                               "No se ha encontrado Claude Code en $GIVEN (--claude-path)."
    else L "Claude Code (the claude command) was not found." \
           "No se ha encontrado Claude Code (el comando claude)."
    fi
    echo
    echo "$(L "It can be installed with its official installer:" "Se puede instalar con su instalador oficial:")  $CLAUDE_INSTALL_CMD"
    if confirm_install "$(L "Install it now with the official installer?" "¿Instalarlo ahora con el instalador oficial?")"; then
        if [ -n "$TEST_MISSING" ]; then
            L "Test: nothing is installed." "Prueba: no se instala nada."; echo
        else
            echo "$(L "Running:" "Ejecutando:") $CLAUDE_INSTALL_CMD"
            failed=$(L "The Claude Code installer did not finish correctly." \
                       "El instalador de Claude Code no ha terminado bien.")
            if [ "$TTY" = 1 ]; then sh -c "$CLAUDE_INSTALL_CMD" < /dev/tty || echo "$failed"
            else sh -c "$CLAUDE_INSTALL_CMD" || echo "$failed"
            fi
            # The official installer puts claude in ~/.local/bin, which may not be in PATH yet
            PATH="$HOME/.local/bin:$PATH"; export PATH
            CLAUDE=$(find_claude "")
            if [ -n "$CLAUDE" ] && [ -n "$GIVEN" ]; then
                L "Using $CLAUDE instead of $GIVEN." "Se usa $CLAUDE en lugar de $GIVEN."; echo
                # Replace the --claude-path value in the setup arguments
                n=$#; prev=""
                while [ "$n" -gt 0 ]; do
                    a=$1; shift; n=$((n - 1))
                    case $a in --claude-path=*) a="--claude-path=$CLAUDE" ;; esac
                    [ "$prev" = "--claude-path" ] && a=$CLAUDE
                    set -- "$@" "$a"; prev=$a
                done
            fi
        fi
    fi
    [ -n "$CLAUDE" ] || fail "$(L "Claude Code (the claude command) is required and was not found.
Install it from https://claude.com/claude-code:  $CLAUDE_INSTALL_CMD
If it is already installed somewhere else, add --claude-path <path to claude>." \
"Hace falta Claude Code (el comando claude) y no se ha encontrado.
Instálalo desde https://claude.com/claude-code:  $CLAUDE_INSTALL_CMD
Si ya está instalado en otro sitio, añade --claude-path <ruta de claude>.")
$NEW_WINDOW"
fi
echo "Claude Code: $CLAUDE"
echo

if [ -n "$TEST_MISSING" ]; then
    L "Test finished: nothing was installed or changed, and the setup did not run." \
      "Prueba terminada: no se ha instalado ni cambiado nada, y la configuración no se ha ejecutado."
    echo
    exit 0
fi

# --- Setup ------------------------------------------------------------------------
# exec replaces this shell, so the EXIT trap would not run: clean up now.
rm -rf "$TMP"
trap - EXIT INT TERM
# The bridge gets the same language (--lang, saved in latiddo.json).
# With "curl ... | sh" stdin is the script itself: read the answers from the terminal.
if [ ! -t 0 ] && (: < /dev/tty) 2>/dev/null; then
    exec "$PY" "$DEST/latiddo_usage_poll.py" --setup --lang "$UI_LANG" "$@" < /dev/tty
fi
exec "$PY" "$DEST/latiddo_usage_poll.py" --setup --lang "$UI_LANG" "$@"
